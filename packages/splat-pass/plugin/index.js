// @viro-external/splat-pass — Expo config plugin
//
// Survives `expo prebuild --clean`. Injects:
//   1. android/app/src/main/jni/CMakeLists.txt + OnLoad.cpp — the
//      combined CMake that builds BOTH libappmodules.so (RN New Arch
//      turbo modules including PlatformConstants) and libsplat_pass.so.
//   2. android/app/build.gradle externalNativeBuild block pointing at
//      that CMakeLists with the four -D vars splat-pass needs
//      (VIROCORE_INCLUDE_DIR, VIROCORE_ANDROID_INCLUDE_DIR,
//      VIROCORE_LIB_DIR, ANDROID_STL).
//
// Per the host-app integration docs: virocore + viro forks must live
// as workspace siblings of the consuming app. The default paths assume
// the canonical layout (<workspaceRoot>/virocore + <workspaceRoot>/viro).
// Override via plugin options if your layout differs.

const { withDangerousMod, withAppBuildGradle } = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const DEFAULT_OPTIONS = {
  // Path to virocore source, relative to project root.
  virocoreDir: '../virocore',
  // ABI to build (arm64-v8a covers Quest/PICO; aarch64-style devices).
  abi: 'arm64-v8a',
};

function readOnLoadSource(projectRoot) {
  const rnTemplate = path.join(
    projectRoot,
    'node_modules/react-native/ReactAndroid/cmake-utils/default-app-setup/OnLoad.cpp'
  );
  return fs.readFileSync(rnTemplate, 'utf8');
}

function writeHostCMake(projectRoot) {
  const jniDir = path.join(projectRoot, 'android/app/src/main/jni');
  fs.mkdirSync(jniDir, { recursive: true });

  const cmake = `# Host app CMake — generated by @viro-external/splat-pass plugin.
# Builds libappmodules.so (RN New Arch turbo modules + autolinking)
# AND libsplat_pass.so via add_subdirectory.

cmake_minimum_required(VERSION 3.22)
project(appmodules)

include(\${REACT_ANDROID_DIR}/cmake-utils/ReactNative-application.cmake)

add_subdirectory(
  \${CMAKE_CURRENT_SOURCE_DIR}/../../../../../node_modules/@viro-external/splat-pass/native
  splat_pass_build
)
`;
  fs.writeFileSync(path.join(jniDir, 'CMakeLists.txt'), cmake);
  fs.writeFileSync(path.join(jniDir, 'OnLoad.cpp'), readOnLoadSource(projectRoot));
}

function withSplatPassFiles(config, opts) {
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      writeHostCMake(cfg.modRequest.projectRoot);
      return cfg;
    },
  ]);
}

function withSplatPassGradle(config, opts) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.contents.includes('@viro-external/splat-pass plugin block')) {
      return cfg;
    }

    const externalBlock = `
    // @viro-external/splat-pass plugin block — combined CMake for
    // libappmodules.so + libsplat_pass.so.
    externalNativeBuild {
        cmake {
            path "src/main/jni/CMakeLists.txt"
            version "3.22.1"
        }
    }
`;

    const defaultConfigArgs = `
        externalNativeBuild {
            cmake {
                arguments  "-DANDROID_STL=c++_shared",
                           "-DVIROCORE_INCLUDE_DIR=\${rootDir}/${opts.virocoreDir}/ViroRenderer",
                           "-DVIROCORE_ANDROID_INCLUDE_DIR=\${rootDir}/${opts.virocoreDir}/android/sharedCode/src/main/cpp",
                           "-DVIROCORE_LIB_DIR=\${rootDir}/${opts.virocoreDir}/android/viroreact/build/intermediates/library_and_local_jars_jni/release/jni/${opts.abi}"
                abiFilters "${opts.abi}"
            }
        }
`;

    // Inject the top-level externalNativeBuild block right before the
    // last closing brace of the `android { ... }` block. AGP supports
    // exactly one externalNativeBuild per android block; if the user
    // added their own, this plugin would clobber it — we look for that
    // sentinel and bail with a clear error.
    const hasExternalBlock = /\bexternalNativeBuild\s*\{\s*cmake/m.test(cfg.modResults.contents);
    if (hasExternalBlock) {
      throw new Error(
        '@viro-external/splat-pass plugin: app/build.gradle already declares an externalNativeBuild block. ' +
          'Remove it or merge with the splat-pass block manually (see INTEGRATION.md).'
      );
    }

    cfg.modResults.contents = cfg.modResults.contents.replace(
      /(\n\s*defaultConfig\s*\{[^}]*?\n\s*buildConfigField[^\n]*\n\s*\})/m,
      (match) => match.replace(/(\n\s*\})\s*$/m, `${defaultConfigArgs}$1`)
    );

    // Append the top-level externalNativeBuild block before the FINAL
    // closing brace of the `android { ... }` block.
    cfg.modResults.contents = cfg.modResults.contents.replace(
      /(\n\s*androidResources\s*\{[\s\S]*?\}\s*)\n\}/,
      `$1${externalBlock}\n}`
    );
    return cfg;
  });
}

module.exports = function withSplatPass(config, options = {}) {
  const opts = { ...DEFAULT_OPTIONS, ...options };
  config = withSplatPassFiles(config, opts);
  config = withSplatPassGradle(config, opts);
  return config;
};
