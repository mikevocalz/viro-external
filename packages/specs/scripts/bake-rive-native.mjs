#!/usr/bin/env node
/**
 * Bake a scene's Rive panels for native Viro, through the same pipeline the
 * Specs build uses: resolveRivePanel reads clips and buttons from each file,
 * bakeRive renders them. The output is a GIF per clip plus an index the app
 * imports, so a RivePanel plays the same clips, state graph and buttons on a
 * headset as on Specs.
 *
 *   pnpm specs:bake-rive-native -- --entry scene.tsx --out apps/mobile/assets/rive-baked
 *
 * Then: `import { RIVE_BAKES } from "./assets/rive-baked";`
 *       `<RivePanel tag="lesson" baked={RIVE_BAKES.lesson} … />`
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { compileUiScene, resolveRivePanel } from "./compile-ui-scene.mjs";
import { bakeRive } from "./bake-rive.mjs";

export async function bakeRiveNative(entry, outDir) {
  const result = compileUiScene(entry);
  const entries = [];
  for (const bake of result.riveBakes) {
    const panelId = bake.nodeId.replace(/-rive$/, "");
    const dir = path.join(outDir, panelId);
    mkdirSync(dir, { recursive: true });
    const panel = await resolveRivePanel(bake, entry, result.diagnostics);
    const manifest = await bakeRive({
      riv: panel.riv,
      artboard: bake.artboard,
      clips: panel.clips,
      width: bake.resolution,
      clipsDir: dir,
    });
    const clips = Object.entries(manifest.clips).map(([name, clip]) => {
      const durationMs = Math.round(((clip.end - clip.start + 1) / manifest.fps) * 1000);
      return `      ${JSON.stringify(name)}: { source: require(${JSON.stringify("./" + panelId + "/" + name + ".gif")}), loop: ${clip.loop}, durationMs: ${durationMs} },`;
    });
    entries.push(`  ${JSON.stringify(panelId)}: {
    aspect: ${manifest.width / manifest.height},
    clips: {
${clips.join("\n")}
    },
    play: ${JSON.stringify(panel.play)},
    next: ${JSON.stringify(bake.next ?? {})},
    onSelect: ${JSON.stringify(bake.onSelect ?? {})},
    buttons: ${JSON.stringify(panel.buttons)},
  },`);
  }
  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    path.join(outDir, "index.ts"),
    `// Generated by @viro-external/specs bake-rive-native from ${path.basename(entry)}. Do not edit;
// rerun \`pnpm specs:bake-rive-native\` after changing a Rive file.
import type { RiveBaked } from "@viro-external/ui";

export const RIVE_BAKES: Record<string, RiveBaked> = {
${entries.join("\n")}
};
`
  );
  return result;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const arg = (name) => {
    const index = process.argv.indexOf(name);
    return index >= 0 ? process.argv[index + 1] : undefined;
  };
  const entry = arg("--entry");
  const out = arg("--out");
  if (!entry || !out) {
    console.error("Usage: pnpm specs:bake-rive-native -- --entry scene.tsx --out <app assets dir>");
    process.exit(1);
  }
  const result = await bakeRiveNative(entry, out);
  for (const message of result.diagnostics) console.warn("warning: " + message);
  console.log("Baked " + result.riveBakes.length + " Rive panel(s) to " + out);
}
