#!/usr/bin/env node
/**
 * Compile a @viro-external/ui scene for Specs.
 *
 *   pnpm specs:scene -- --entry examples/harlem-courts.tsx \
 *     --project "/path/to/Lens Project" [--parent platform-lab-root]
 *
 * The entry's default export is the JSX tree (or a function returning it). It
 * may also export `resolveSource(source, kind)` to map bundled assets to Lens
 * registry ids. Writes Assets/ViroSpecs/generated/ViroUIScene.ts, which the
 * generated scene host appends to its scene.
 */
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const require = createRequire(import.meta.url);

function arg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

export function compileUiScene(entryPath, { parentId } = {}) {
  const { loadScene } = require("./ui-scene-loader.cjs");
  const scene = loadScene(path.resolve(entryPath));
  const { toPortableScene } = require("@viro-external/ui");
  const tree = typeof scene.default === "function" ? scene.default() : scene.default;
  return toPortableScene(tree, { parentId, resolveSource: scene.resolveSource });
}

export function sceneModule(result, entryPath) {
  return [
    "// Generated by @viro-external/specs from " + entryPath + ". Do not edit;",
    "// change the scene file and run `pnpm specs:scene` instead.",
    "export const VIRO_UI_NODES: any[] = " + JSON.stringify(result.nodes, null, 2) + ";",
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const entry = arg("--entry");
  const project = arg("--project");
  if (!entry || !project) {
    console.error("Usage: pnpm specs:scene -- --entry scene.tsx --project /path/to/LensProject [--parent nodeId]");
    process.exit(1);
  }
  const result = compileUiScene(entry, { parentId: arg("--parent") });
  for (const message of result.diagnostics) console.warn("warning: " + message);
  const out = path.join(project, "Assets", "ViroSpecs", "generated", "ViroUIScene.ts");
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, sceneModule(result, path.relative(process.cwd(), path.resolve(entry))));
  console.log("Wrote " + result.nodes.length + " Specs nodes to " + out);
}
