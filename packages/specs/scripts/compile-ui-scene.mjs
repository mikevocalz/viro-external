#!/usr/bin/env node
/**
 * Compile a @viro-external/ui scene for Specs.
 *
 *   pnpm specs:scene -- --entry examples/harlem-courts.tsx \
 *     --project "/path/to/Lens Project" [--parent platform-lab-root]
 *
 * The entry's default export is the JSX tree (or a function returning it). It
 * may also export `resolveSource(source, kind)` to map bundled assets to Lens
 * registry ids, and `animations` (the ViroAnimations registrations it uses).
 * Writes Assets/ViroSpecs/generated/ViroGeneratedSceneHost.ts, the scene host
 * the Lens project runs. Only the file content is written, so Lens keeps the
 * script's .meta and the scene's reference to it.
 */
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const require = createRequire(import.meta.url);

function arg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

export function compileUiScene(entryPath, { parentId } = {}) {
  const { loadScene } = require("./ui-scene-loader.cjs");
  const scene = loadScene(path.resolve(entryPath));
  const { toPortableScene } = require("@viro-external/ui");
  const tree = typeof scene.default === "function" ? scene.default() : scene.default;
  return toPortableScene(tree, {
    parentId,
    resolveSource: scene.resolveSource,
    animations: scene.animations,
  });
}

/**
 * The Lens scene host: the mapped scene plus the class that applies it. Same
 * shape as the fork's static compiler output (`viro-specs-compile.cjs`
 * lensTs), so the hosts in ../lens read it unchanged.
 */
export function hostModule(result, entryPath) {
  const json = (value) => JSON.stringify(value, null, 2);
  return `// Generated by @viro-external/specs from ${entryPath}. Do not edit;
// change the scene file and run \`pnpm specs:scene\` instead.
import { ViroSpecsAnimationHost } from "../lens/ViroSpecsAnimationHost";
import { ViroSpecsInteractionHost } from "../lens/ViroSpecsInteractionHost";
import { ViroSpecsNavigationHost } from "../lens/ViroSpecsNavigationHost";
import { ViroSpecsRuntimeHost } from "../lens/ViroSpecsRuntimeHost";

const GENERATED_SCENE: any = ${json({ version: 1, nodes: result.nodes })};
const GENERATED_POLYLINES: any[] = ${json(result.polylines)};
const GENERATED_INTERACTIONS: any[] = ${json(result.interactions)};
const GENERATED_ANIMATIONS: any[] = ${json(result.animations)};

${HOST_CLASS}`;
}

// Applies the four tables above through the hosts in ../lens.
const HOST_CLASS = `@component
export class ViroGeneratedSceneHost extends BaseScriptComponent {
  @input runtimeHostObject: SceneObject;
  @input interactionHostObject: SceneObject;
  @input animationHostObject: SceneObject;
  @input navigationHostObject: SceneObject;

  private teardown: (() => void) | null = null;

  onAwake(): void {
    this.createEvent("OnStartEvent").bind(() => this.restartGeneratedScene());
    this.createEvent("OnDestroyEvent").bind(() => this.stopGeneratedScene());
  }

  stopGeneratedScene(): void {
    this.teardown?.();
    this.teardown = null;
  }

  restartGeneratedScene(): void {
    this.stopGeneratedScene();
    const runtime = this.runtimeHostObject.getComponent(
      ViroSpecsRuntimeHost.getTypeName()
    ) as ViroSpecsRuntimeHost | null;
    const interaction = this.interactionHostObject.getComponent(
      ViroSpecsInteractionHost.getTypeName()
    ) as ViroSpecsInteractionHost | null;
    const animation = this.animationHostObject.getComponent(
      ViroSpecsAnimationHost.getTypeName()
    ) as ViroSpecsAnimationHost | null;
    const navigation = this.navigationHostObject.getComponent(
      ViroSpecsNavigationHost.getTypeName()
    ) as ViroSpecsNavigationHost | null;

    if (!runtime) {
      throw new Error("Generated Viro scene requires ViroSpecsRuntimeHost.");
    }

    if (GENERATED_INTERACTIONS.length && !interaction) throw new Error("Generated Viro interactions require ViroSpecsInteractionHost.");
    if (GENERATED_ANIMATIONS.length && !animation) throw new Error("Generated Viro animations require ViroSpecsAnimationHost.");
    if (GENERATED_POLYLINES.length && !navigation) throw new Error("Generated Viro polylines require ViroSpecsNavigationHost.");

    this.teardown = () => {
      if (interaction && !isNull(interaction)) for (const item of GENERATED_INTERACTIONS) interaction.remove(item.nodeId);
      if (animation && !isNull(animation)) for (const item of GENERATED_ANIMATIONS) animation.stop(item.nodeId);
      if (navigation && !isNull(navigation)) navigation.clearRoute();
      if (!isNull(runtime)) runtime.clear();
    };
    runtime.applySceneSnapshot(GENERATED_SCENE);

    if (interaction) {
      for (const item of GENERATED_INTERACTIONS) {
        interaction.setInteractable(item.nodeId, true);
        if (item.manipulation) {
          interaction.setManipulationEnabled(item.nodeId, true);
        }
      }
    }

    if (animation) {
      for (const item of GENERATED_ANIMATIONS) {
        animation.play(item.nodeId, item.plan);
      }
    }

    if (navigation) {
      for (const line of GENERATED_POLYLINES) {
        navigation.presentPolyline(line);
      }
    }
  }
}
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const entry = arg("--entry");
  const project = arg("--project");
  if (!entry || !project) {
    console.error("Usage: pnpm specs:scene -- --entry scene.tsx --project /path/to/LensProject [--parent nodeId]");
    process.exit(1);
  }
  const result = compileUiScene(entry, { parentId: arg("--parent") });
  for (const message of result.diagnostics) console.warn("warning: " + message);
  const out = path.join(project, "Assets", "ViroSpecs", "generated", "ViroGeneratedSceneHost.ts");
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, hostModule(result, path.relative(process.cwd(), path.resolve(entry))));
  console.log(
    "Wrote " + result.nodes.length + " nodes, " + result.interactions.length + " interactions, " +
      result.animations.length + " animations and " + result.polylines.length + " polylines to " + out
  );
}
