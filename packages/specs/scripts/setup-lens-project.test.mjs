// specs:setup without Lens Studio: argument parsing, the Preview failure
// filter, and that the package list and the wire script match the runtime.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { loadManifest, kitSeams } from "./lib/lens-runtime-manifest.mjs";
import { SETUP_MATERIALS, SETUP_PACKAGES, SETUP_STEPS, parseSetupArgs, previewFailures } from "./setup-lens-project.mjs";

test("parses --project, --create and a step subset in run order", () => {
  const options = parseSetupArgs(["--project", "/tmp/Lens", "--create", "--steps", "wire,preflight"]);
  assert.equal(options.project, "/tmp/Lens");
  assert.equal(options.create, true);
  assert.deepEqual(options.steps, ["preflight", "wire"]);
  assert.deepEqual(parseSetupArgs(["--project", "/tmp/Lens"]).steps, SETUP_STEPS);
  assert.throws(() => parseSetupArgs([]), /Usage/);
  assert.throws(() => parseSetupArgs(["--project", "/tmp/Lens", "--steps", "deploy"]), /Unknown step deploy/);
  assert.throws(() => parseSetupArgs(["--project", "/tmp/Lens", "--yes"]), /Unknown argument --yes/);
});

test("Preview failures: errors and VS5xxx errors fail, warnings and renderer notices do not", () => {
  assert.deepEqual(
    previewFailures({
      errors: ["W 22:40:27.879 [CamPlat.LensCore.Scn.Rendering.SnapGraphics] Depth format Depth24UnormStencil8 is not renderable"],
      prints: ['I 22:40:27.848 [Preview 1] [viro-specs-host] warning VS5008 (stage) node hello-body: Text "hello-body" maxLines 3 is approximated.'],
    }),
    []
  );
  const failing = previewFailures({
    errors: ["E 10:00:00.000 [Preview 1] TypeError: undefined is not a function"],
    prints: ["I 10:00:00.000 [Preview 1] [viro-specs-host] error VS5005 (stage) Staging failed"],
  });
  assert.equal(failing.length, 2);
  // A refresh whose Lens never ran its scripts is a failure, not an empty pass.
  assert.deepEqual(
    previewFailures({ errors: [], prints: [], tail: "I 00:34:26.474 Lens has been reset\nD 00:34:26.505 Some assets are not ready for preview or a script failed to compile: TypeScript is not compiled" }),
    ["Preview did not run the Lens scripts: TypeScript is not compiled."]
  );
});

test("installs the 2.x line the runtime manifest requires, plus the Preview inspector", () => {
  const manifest = loadManifest();
  const requirements = [
    ...kitSeams(manifest).map(({ lines }) => lines["2"]),
    ...manifest.requiredPackages,
    manifest.validationPackages.find((item) => item.package === "AiPreviewAgentInspect.lspkg"),
  ];
  assert.deepEqual(SETUP_PACKAGES.map((pkg) => pkg.file + ".lspkg").sort(), requirements.map((item) => item.package).sort());
  for (const pkg of SETUP_PACKAGES) {
    assert.equal(pkg.version, requirements.find((item) => item.package === pkg.file + ".lspkg").minVersion, pkg.file);
  }
});

test("the wire script names real runtime components, inputs and setup materials", () => {
  const wire = readFileSync(new URL("./lens-editor/wire-scene-host.ts", import.meta.url), "utf8");
  const source = (file) => readFileSync(new URL("../lens/" + file, import.meta.url), "utf8");
  const inputsOf = (file) => [...source(file).matchAll(/@input[\s\S]*?\n\s+(\w+)\s*[:=?]/g)].map((m) => m[1]);
  const owners = {
    AssetRegistry: "ViroSpecsAssetRegistry.ts",
    SceneHost: "ViroSpecsSceneControllerHost.ts",
    ExperienceHost: "ViroSpecsExperienceLensView.ts",
  };
  for (const [, owner, name] of wire.matchAll(/setInput\(\w+, "(\w+)", "(\w+)"/g)) {
    if (owner === "GeneratedHost") continue; // generated by viro-specs-compile; checked at run time
    assert.ok(inputsOf(owners[owner]).includes(name), `${owner}.${name} is not an @input of ${owners[owner]}`);
  }
  for (const [, name] of wire.matchAll(/ensureScript\(\w+, "(\w+)"\)/g)) {
    if (name === "ViroGeneratedSceneHost") continue;
    assert.ok(loadManifest().files.production.includes(name + ".ts"), name);
  }
  for (const [, name] of wire.matchAll(/material\("(\w+)"\)/g)) {
    assert.ok(SETUP_MATERIALS.some((m) => m.name === name), name);
  }
  // Lens compiler traps: no logical assignment, no truthiness narrowing of .ok.
  assert.doesNotMatch(wire, /\?\?=|\|\|=|&&=/);
});
